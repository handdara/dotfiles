    local ts = u.timestamp()
    return sn(nil, fmt(bDaily, {
        t('[[p' .. u.dtnum2str(ts.mo_num) .. '-' .. ts.mo .. '-' .. ts.yr .. ']]'),
        t(ts.dy .. ts.mo .. ts.yr .. ', ' .. ts.wd),
        daySchedules[ts.wd_num],
        i(1, ':?: ...'),
        i(2, ':?: ...'),
        i(3, ':?: ...'),
    }))
end))

